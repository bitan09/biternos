import { readFile, writeFile } from "./filemanager.service";

const PROPERTIES_FILE = "server.properties";

/** Parses a Java `.properties`-style file into a plain key/value object. */
export function parseProperties(raw: string): Record<string, string> {
  const result: Record<string, string> = {};
  for (const line of raw.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const idx = trimmed.indexOf("=");
    if (idx === -1) continue;
    result[trimmed.slice(0, idx).trim()] = trimmed.slice(idx + 1).trim();
  }
  return result;
}

export function serializeProperties(props: Record<string, string>): string {
  const lines = ["# Generated by Bitarnos", `#${new Date().toString()}`];
  for (const [key, value] of Object.entries(props)) {
    lines.push(`${key}=${value}`);
  }
  return lines.join("\n") + "\n";
}

export async function getServerProperties(dataRoot: string): Promise<Record<string, string>> {
  try {
    const raw = await readFile(dataRoot, PROPERTIES_FILE);
    return parseProperties(raw);
  } catch {
    return {}; // file doesn't exist yet (server never booted) — return empty defaults
  }
}

export async function updateServerProperties(dataRoot: string, patch: Record<string, string>): Promise<void> {
  const current = await getServerProperties(dataRoot);
  const merged = { ...current, ...patch };
  await writeFile(dataRoot, PROPERTIES_FILE, serializeProperties(merged));
}
